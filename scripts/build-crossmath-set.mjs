// Builds packages/engine/src/crossmath/set.ts — the Crossmath puzzles the game
// ships — from the engine's own seeded generator:
//
//   npm run build -w packages/engine && node scripts/build-crossmath-set.mjs
//
// The same seeds always make the same puzzles, so running it again changes
// nothing unless the generator or PER_LEVEL did. Easy No. 1 is the sample from
// the proposal (2 + 3 + 5 = 10 …), kept first by hand. Every puzzle is
// checked once more for exactly one solution before it is written.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Crossmath } from "../packages/engine/dist/index.js";

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../packages/engine/src/crossmath/set.ts");
const PER_LEVEL = { easy: 60, medium: 60, hard: 50, expert: 40 };

export const SAMPLE = "3|++,++,++|+++,+++|2.3.5,4.1.5,6.4.10|100,010,001";

const set = {};
for (const level of Crossmath.LEVELS) {
  const started = Date.now();
  const lines = [];
  for (let number = 1; number <= PER_LEVEL[level]; number++) {
    const text = level === "easy" && number === 1 ? SAMPLE : Crossmath.encodePuzzle(Crossmath.generatePuzzle(level, number));
    const puzzle = Crossmath.decodePuzzle(text, level, `${level}-${number}`);
    if (Crossmath.countSolutions(puzzle) !== 1) throw new Error(`${puzzle.id} is not unique`);
    lines.push(text);
  }
  set[level] = lines;
  console.log(`${level}: ${lines.length} puzzles in ${((Date.now() - started) / 1000).toFixed(1)} s`);
}

const body = Crossmath.LEVELS.map((level) => `  ${level}: [\n${set[level].map((line) => `    "${line}"`).join(",\n")}\n  ]`).join(",\n");
fs.writeFileSync(
  out,
  `// Generated by scripts/build-crossmath-set.mjs — do not edit by hand.\n` +
    `// One puzzle per line: "n|row ops|col ops|values|given" (rules.ts → decodePuzzle).\n` +
    `export const CROSSMATH_SET: Record<"easy" | "medium" | "hard" | "expert", readonly string[]> = {\n${body}\n};\n`
);
console.log(`Wrote ${path.relative(process.cwd(), out)}`);
